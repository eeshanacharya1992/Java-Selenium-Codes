package Package;

public class IfElseIfExample3 {

	public static void main(String[] args) {
		int no=50;
		if(no<30)
		{
			System.out.println("Artificial Intelligence");
		}
		else if(no==50)
		{
			System.out.println("Machine Learning");
		}
		else if( no<=50)
		{
			System.out.println("Deep Learning");
		}
		else if(no>=50)
		{
			System.out.println("BDD Cucumber");
		}
		else
		{
			System.out.println("Multiple concepts");
		}

	}

}
