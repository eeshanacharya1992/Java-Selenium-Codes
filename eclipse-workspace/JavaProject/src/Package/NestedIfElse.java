package Package;

public class NestedIfElse {

	public static void main(String[] args) {
		int a=34;
		
		if(a==34)
		{
			if(a>=34)
			{
				if(a<=34)
				{
					System.out.println("Hello");
				}
				else
				{
					System.out.println("World");
				}
			}
			else
			{
				System.out.println("Have a superb day");
			}
		}
		else
		{
			System.out.println("Good morning");
		}
	}

}
